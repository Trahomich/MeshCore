#pragma once

// LuFree ("luchik"): калибровка 5-позиционного стика.
//
// Пины стика НЕИЗВЕСТНЫ (устройство собрано навесным монтажом, документации
// нет — см. обсуждение задачи #14, посты #60–#61). В отличие от e-paper,
// стик пассивно найти нельзя: ненажатые кнопки не отличить от свободных
// пинов, а какая линия «вверх», а какая «вниз» не определить вообще.
// Поэтому — ИНТЕРАКТИВНАЯ КАЛИБРОВКА один раз при первом старте:
//   1) на экране (если найден) подсказка «нажмите ВВЕРХ» и т.д. по порядку
//      UP, DOWN, LEFT, RIGHT, OK; без экрана — LED мигает 1..5 раз;
//   2) прошивка смотрит свободные пины (кроме занятых экраном) и ловит
//      устойчивое (~50 мс) отклонение от уровня покоя — это и есть линия;
//   3) полярность определяется автоматически: сначала кнопки-на-GND
//      (нажатие = LOW при внутренней подтяжке вверх), затем 8 с на
//      кнопки-на-VCC (нажатие = HIGH при подтяжке вниз);
//   4) результат (5 пинов + полярность) сохраняется в InternalFS /stick.cfg.
//
// Перекалибровка: зажать любое направление стика при включении и держать
// ~3 секунды — конфиг игнорируется и калибровка запустится снова.
//
// Кнопки (user_btn=OK, joystick_up/down/left/right, back_btn) — ссылки на
// placement-new объекты (пины известны только в рантайме), конструируются
// в lufreeStickSetup() ДО ui_task.begin(); объявления — variants/promicro/target.h.

#include <Arduino.h>

struct StickPins {
  int8_t up, down, left, right, ok;   // Arduino-пины, -1 = не найдено
  uint8_t activeLow;                  // 1: нажатие = LOW (кнопки на GND); 0: нажатие = HIGH (на VCC)
  bool valid() const { return up >= 0 && down >= 0 && left >= 0 && right >= 0 && ok >= 0; }
};

// Загрузка/сохранение конфигурации (InternalFS, файл /stick.cfg).
StickPins lufreeLoadStick();
void lufreeSaveStick(const StickPins &s);

// Интерактивная калибровка (см. шапку файла). disp == NULL — только LED.
// Возвращает invalid-структуру при отказе/таймауте.
StickPins stickCalibrate(class DisplayDriver *disp);

// Вызывается из main.cpp до ui_task.begin(): загружает /stick.cfg (или
// запускает калибровку) и конструирует кнопки. При неудаче кнопки
// конструируются на безопасный неиспользуемый пин (PIN_USER_BTN, уровень
// покоя) — стик просто не работает, UI/BLE/LoRa не задеты.
void lufreeStickSetup(class DisplayDriver *disp);
